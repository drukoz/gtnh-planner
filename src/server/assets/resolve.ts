// Turns what the planner draws into textures (spec §3.8): a `BlockRef` into six faces, an item or fluid key into an
// icon, a cover item into its in-world overlay. GT's texture dump comes first, then the curated tables, the texture
// names of the extracted jars and, last, the files found by name (`names.ts`), in architecture §11.43 (a)'s order;
// whatever does not resolve gets a plain colour. Pure functions over loaded data: no file access.

import { isFluidKey, parseItemKey, type StuffKey } from '../../shared/keys.ts';
import {
  FACES, hashColor, KIND_COLORS, rotateFaces,
  type BlockFaces, type CoverLayers, type Face, type IconDescriptor, type PipeLayers, type Rgb, type TextureLayer,
} from '../../shared/types/assets.ts';
import type { BlockRef, Pack } from '../../shared/types/pack.ts';
import { curatedBlock, curatedItem, type CuratedLayer } from './curated.ts';
import {
  coverLayers, facesFrom, gtBlockFaces, gtFluidIcon, gtItemIcon, gtMachineFaces, gtMaterialBlockFaces, gtOreFaces, gtTemplateIcon, type CopyResolver,
} from './gt-faces.ts';
import { iconPath, isWhite, type AssetIndex } from './index.ts';
import { AUTOGENERATED_FLUID, facesByName, fileByName, fluidFile, modDomains, nameIndex, textureNameFaces, textureNameFile } from './names.ts';
import type { TexturesDump } from './textures-dump.ts';

/** Icons rendered by NEI itself (Task 11's NEI index implements it). */
export interface IconSource { icon(key: StuffKey): TextureLayer | null }
/** All the resolver reads of a pack; a full `Pack` fits. */
export type PackView = Pick<Pack, 'items' | 'machines' | 'materials' | 'fluidContainers'>;
export interface AssetSources { index: AssetIndex; dump: TexturesDump | null; nei: IconSource | null; pack: PackView | null }

const GT_MACHINES = 'gregtech:gt.blockmachines';   // its item meta is the MTE id
const FLUID_PREFIX = 'fluid:';                     // as shared/keys.ts fluidKey() writes it
const CANONICAL_FACING = 2;                        // front on north
/** A copy nested deeper than this resolves to nothing, so a block that copies itself ends instead of recursing. */
const MAX_COPY_DEPTH = 4;
/** The meta of a fluid block's source (still) state, whose face a fluid's icon shows. */
const FLUID_SOURCE_META = 0;

type Faces = Record<Face, TextureLayer[]>;
/** Canonical faces and where they came from: GT's texture dump, or the jar files (curated table, texture name, file name). */
interface FoundFaces { faces: Faces; from: 'gt' | 'jar' }
/** An icon's layers and where they came from. */
interface FoundIcon { layers: TextureLayer[]; source: 'nei' | 'gt' | 'jar' }
interface ItemRef { id: string; meta: number }

/** A fresh RGB triple, so callers never share (or alter) the tables' arrays; drops the alpha of an RGBA. */
function rgbOf(c: readonly [number, number, number, ...number[]]): Rgb {
  return [c[0], c[1], c[2]];
}

function fluidName(key: StuffKey): string {
  return key.slice(FLUID_PREFIX.length);
}

function emptyFaces(): Faces {
  return { down: [], up: [], north: [], south: [], west: [], east: [] };
}

function allFaces(layer: TextureLayer): Faces {
  const faces = {} as Faces;
  for (const face of FACES) faces[face] = [layer];
  return faces;
}

/** One extracted file per face as jar faces; null for no files. */
function pathFaces(index: AssetIndex, paths: Record<Face, string> | null): FoundFaces | null {
  if (paths === null) return null;
  const faces = {} as Faces;
  for (const face of FACES) {
    const layer = index.layer(paths[face]);
    faces[face] = layer === null ? [] : [layer];
  }
  return { faces, from: 'jar' };
}

/** One extracted file as a jar icon, tinted with `tint` (white draws it as it is); null for no path or no file. */
function jarIcon(index: AssetIndex, path: string | null, tint?: Rgb): FoundIcon | null {
  const layer = path === null ? null : index.layer(path, { tint });
  return layer === null ? null : { layers: [layer], source: 'jar' };
}

/** `layer` in `color` instead of its own tint; white draws it as it is, as `AssetIndex.layer` drops a white tint. */
function inColor(layer: TextureLayer, color: Rgb): TextureLayer {
  const { tint: _, ...rest } = layer;
  return isWhite(color) ? rest : { ...rest, tint: rgbOf(color) };
}

/** The mod and registry name of a registry id (`IC2` and `itemPartCircuit` of `IC2:itemPartCircuit`); null without either. */
function splitId(id: string): { mod: string; name: string } | null {
  const colon = id.indexOf(':');
  return colon <= 0 || colon === id.length - 1 ? null : { mod: id.slice(0, colon), name: id.slice(colon + 1) };
}

/** Resolves a `CopyRef` at nesting level `depth` (1 = a copy in the block asked for). */
function copier(src: AssetSources, depth: number): CopyResolver {
  return (block, meta, side) => {
    const face = FACES[side];
    if (depth > MAX_COPY_DEPTH || face === undefined) return [];
    return blockFaces(src, block, meta, copier(src, depth + 1))?.faces[face] ?? [];
  };
}

/**
 * Block steps after the GT machine (architecture §11.43 (a)): the dump's block table, GT ore block or GT material block
 * (frames, sheetmetal, storage blocks), the curated table, the block's texture name, the file-name rule; first match
 * wins. Without a dump only the curated table and the file-name rule run.
 */
function blockFaces(src: AssetSources, id: string, meta: number, copy: CopyResolver): FoundFaces | null {
  const { index, dump } = src;
  const gt = dump === null ? null
    : gtBlockFaces(dump, id, meta, copy) ?? gtOreFaces(dump, index, id, meta, copy) ?? gtMaterialBlockFaces(dump, index, src.pack, id, meta);
  if (gt !== null) return { faces: gt, from: 'gt' };
  return curatedFaces(index, id, meta) ?? textureNameBlockFaces(src, id, meta) ?? fileNameBlockFaces(src, id, meta);
}

/** The curated table's faces: a face's `layers` when every one is extracted, else the first extracted of its candidates. */
function curatedFaces(index: AssetIndex, id: string, meta: number): FoundFaces | null {
  const curated = curatedBlock(id, meta);
  if (curated === null) return null;
  const faces = {} as Faces;
  for (const face of FACES) {
    const tint = curated.tint?.[face];
    const layers = curatedLayers(index, curated.layers?.[face], tint);
    if (layers !== null) {
      faces[face] = layers;
      continue;
    }
    const layer = index.firstLayer(curated.faces[face], { tint });
    faces[face] = layer === null ? [] : [layer];
  }
  return { faces, from: 'jar' };
}

/** Every curated layer of a face, each cut to its region and in its own tint (else the face's); null without layers or when one is missing. */
function curatedLayers(index: AssetIndex, layers: readonly CuratedLayer[] | undefined, faceTint: Rgb | undefined): TextureLayer[] | null {
  if (layers === undefined) return null;
  const out: TextureLayer[] = [];
  for (const curated of layers) {
    const layer = index.firstLayer(curated.paths, { tint: curated.tint ?? faceTint, region: curated.region });
    if (layer === null) return null;
    out.push(layer);
  }
  return out;
}

/** The dump's texture name of the block: its file on every face, else each face's file beside it (`<name>_top`, …). */
function textureNameBlockFaces(src: AssetSources, id: string, meta: number): FoundFaces | null {
  const name = src.dump?.textureNames.blocks.get(id);
  if (name === undefined) return null;
  const layer = src.index.layer(iconPath(name, 'blocks'));
  if (layer !== null) return { faces: allFaces(layer), from: 'jar' };
  return pathFaces(src.index, textureNameFaces(nameIndex(src.index), name, meta));
}

/** The block's files in `blocks/` by registry name, in the mod's domains (its own alone without a dump). */
function fileNameBlockFaces(src: AssetSources, id: string, meta: number): FoundFaces | null {
  const parts = splitId(id);
  if (parts === null) return null;
  return pathFaces(src.index, facesByName(nameIndex(src.index), modDomains(src.dump, parts.mod), parts.name, meta));
}

/**
 * The first block step, the idle GT machine of `mteId`, alone: a machine the dump lacks or failed on gets nothing, never
 * the machine block's own icon (the real dump has a `gt.blockmachines` table that draws the LV hull side). A ref
 * without `mteId` takes the other block steps (`blockFaces`).
 */
function refFaces(src: AssetSources, ref: BlockRef, copy: CopyResolver): FoundFaces | null {
  if (ref.mteId === undefined) return blockFaces(src, ref.id, ref.meta, copy);
  const gt = src.dump === null ? null : gtMachineFaces(src.dump, ref.mteId, copy);
  return gt === null ? null : { faces: gt, from: 'gt' };
}

/** Spec §3.8: a plain colour by machine kind, the casing colour for casings, else a stable colour per block. */
export function blockFallbackColor(ref: BlockRef, pack: PackView | null): Rgb {
  if (ref.mteId !== undefined) return rgbOf(KIND_COLORS[pack?.machines.get(ref.mteId)?.kind ?? 'other']);
  if (/casing/i.test(ref.id)) return rgbOf(KIND_COLORS.casing);
  return hashColor(`${ref.id}@${ref.meta}`);
}

/**
 * Each block's faces turned so its front points to `facing` (ForgeDirection index, default north); same order as
 * `refs`. A GT pipe also gets `pipe`: its core and arms drawn as its side with nothing connected, its arm tips as its
 * (connected) north face.
 */
export function resolveBlocks(src: AssetSources, refs: readonly BlockRef[], facing?: number): BlockFaces[] {
  return refs.map((ref) => {
    const copy = copier(src, 1);
    const found = refFaces(src, ref, copy);
    const faces = rotateFaces(found?.faces ?? emptyFaces(), facing ?? CANONICAL_FACING);
    const out: BlockFaces = {
      block: ref.mteId === undefined ? { id: ref.id, meta: ref.meta } : { id: ref.id, meta: ref.meta, mteId: ref.mteId },
      faces,
      fallbackColor: blockFallbackColor(ref, src.pack),
      resolved: FACES.every((face) => faces[face].length > 0),
    };
    const pipe = pipeLayers(src, ref, faces, copy);
    if (pipe !== null) out.pipe = pipe;
    return out;
  });
}

/** The pipe layers of an MTE whose dump entry has faces with nothing connected (exported or derived); null otherwise. */
function pipeLayers(src: AssetSources, ref: BlockRef, faces: Faces, copy: CopyResolver): PipeLayers | null {
  const unconnected = ref.mteId === undefined ? undefined : src.dump?.mte.get(ref.mteId)?.unconnected;
  if (unconnected === undefined || unconnected === null) return null;
  const side = facesFrom(unconnected, copy).north;
  return { core: side, arm: [...side], end: [...faces.north] };
}

/** Icon steps in architecture §11.43 (a)'s order: NEI, then the fluid steps or the item steps; null when nothing resolves. */
function iconLayers(src: AssetSources, key: StuffKey): FoundIcon | null {
  const nei = src.nei?.icon(key) ?? null;
  if (nei !== null) return { layers: [nei], source: 'nei' };
  if (isFluidKey(key)) return fluidIcon(src, fluidName(key));
  let item: ItemRef;
  try {
    item = parseItemKey(key);
  } catch {
    return null;   // malformed key: the fallback descriptor, never an error for the whole request
  }
  return gtIcon(src, key) ?? templateIcon(src, key) ?? curatedItemIcon(src, item) ?? itemTextureNameIcon(src, item) ?? itemFileNameIcon(src, item)
    ?? blockIcon(src, item);
}

/**
 * Fluid steps: GT's still, the fluid block's face (0.4.0 `fluids[].block`), a fluid file by name, GT's generic still;
 * every layer in the fluid's colour, source 'gt' for GT's still and 'jar' otherwise. Each needs the dump's row of the
 * fluid (its colour, still and block): GT's fluid files are greyscale until tinted, so without a row a fluid falls back.
 */
function fluidIcon(src: AssetSources, name: string): FoundIcon | null {
  const { dump } = src;
  const gt = dump === null ? null : gtFluidIcon(dump, name);
  if (dump === null || gt === null) return null;
  if (gt.layers.length > 0) return { layers: gt.layers, source: 'gt' };
  return fluidBlockIcon(src, dump.fluids.get(name)?.block, gt.color)
    ?? jarIcon(src.index, fluidFile(nameIndex(src.index), name), gt.color)
    ?? jarIcon(src.index, AUTOGENERATED_FLUID, gt.color);
}

/** The north face of the fluid's block (its source state), each layer in the fluid's colour. */
function fluidBlockIcon(src: AssetSources, block: string | undefined, color: Rgb): FoundIcon | null {
  if (block === undefined) return null;
  const layers = blockFaces(src, block, FLUID_SOURCE_META, copier(src, 1))?.faces.north ?? [];
  return layers.length === 0 ? null : { layers: layers.map((layer) => inColor(layer, color)), source: 'jar' };
}

function gtIcon(src: AssetSources, key: StuffKey): FoundIcon | null {
  const layers = src.dump === null ? null : gtItemIcon(src.dump, src.index, key);
  return layers === null ? null : { layers, source: 'gt' };
}

/** GT's material template icon (metaitem.98/99, BartWorks), by the pack's material data. */
function templateIcon(src: AssetSources, key: StuffKey): FoundIcon | null {
  const layers = src.dump === null ? null : gtTemplateIcon(src.dump, src.index, src.pack, key);
  return layers === null ? null : { layers, source: 'gt' };
}

/** The curated item table's icon: its first extracted file, cut to its region, in its tint. */
function curatedItemIcon(src: AssetSources, item: ItemRef): FoundIcon | null {
  const curated = curatedItem(item.id, item.meta);
  const layer = curated === null ? null : src.index.firstLayer(curated.paths, { tint: curated.tint, region: curated.region });
  return layer === null ? null : { layers: [layer], source: 'jar' };
}

/** The dump's texture name of the item: its file, else the file beside it (numbered `<name>/<meta>` first). */
function itemTextureNameIcon(src: AssetSources, item: ItemRef): FoundIcon | null {
  const name = src.dump?.textureNames.items.get(item.id);
  if (name === undefined) return null;
  return jarIcon(src.index, iconPath(name, 'items'))
    ?? jarIcon(src.index, textureNameFile(nameIndex(src.index), name, 'items', item.meta, 'north'));
}

/**
 * The item's file in `items/` by registry name, in the mod's domains (its own alone without a dump). Never for a block
 * id (an id the dump's `blockIds` lists, so every ItemBlock): a same-named `items/` file is too often another thing's,
 * such as vanilla's bone for Et Futurum's bone block, so a block's item keeps its block face. Without a dump no id
 * counts as a block id.
 */
function itemFileNameIcon(src: AssetSources, item: ItemRef): FoundIcon | null {
  if (src.dump?.blockIds.has(item.id) === true) return null;
  const parts = splitId(item.id);
  if (parts === null) return null;
  return jarIcon(src.index, fileByName(nameIndex(src.index), modDomains(src.dump, parts.mod), parts.name, item.meta, 'items', 'north'));
}

/** The item's block: its north face, else its top (a GT machine item draws its MTE, never the machine block). */
function blockIcon(src: AssetSources, item: ItemRef): FoundIcon | null {
  const ref: BlockRef = item.id === GT_MACHINES ? { id: item.id, meta: item.meta, mteId: item.meta } : { id: item.id, meta: item.meta };
  const block = refFaces(src, ref, copier(src, 1));
  if (block === null) return null;
  const layers = block.faces.north.length > 0 ? block.faces.north : block.faces.up;
  return layers.length === 0 ? null : { layers, source: block.from };
}

/**
 * The colour a client paints while the icon loads or when it has none: a fluid's dump colour, an item's GT material
 * colour (pack first, then the dump's material of that name), else a stable colour per key.
 */
export function iconFallbackColor(key: StuffKey, src: AssetSources): Rgb {
  if (isFluidKey(key)) {
    const color = src.dump?.fluids.get(fluidName(key))?.color;
    return color === undefined ? hashColor(key) : rgbOf(color);
  }
  const material = src.pack?.items.get(key)?.gt?.material;
  if (material !== undefined) {
    const color = src.pack?.materials.get(material)?.rgba ?? src.dump?.materialsByName.get(material)?.rgb;
    if (color !== undefined) return rgbOf(color);
  }
  return hashColor(key);
}

/** One icon per key, same order (duplicates kept). */
export function resolveIcons(src: AssetSources, keys: readonly StuffKey[]): IconDescriptor[] {
  return keys.map((key) => {
    const found = iconLayers(src, key);
    const fallbackColor = iconFallbackColor(key, src);
    return found === null ? { key, layers: [], source: 'fallback', fallbackColor } : { key, layers: found.layers, source: found.source, fallbackColor };
  });
}

/**
 * GT's in-world overlay of each cover item (architecture §11.14), same order; `layers` is empty without a dump or for
 * an item that is not a cover, and the 3D view then draws the item icon.
 */
export function resolveCovers(src: AssetSources, items: readonly StuffKey[]): CoverLayers[] {
  return items.map((item) => ({ item, layers: (src.dump === null ? null : coverLayers(src.dump, item, copier(src, 1))) ?? [] }));
}
