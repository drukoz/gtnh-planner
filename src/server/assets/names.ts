// Textures found by file name (spec §3.8, architecture §11.43 (a)): the icons IC2, Forestry, BOP, Ztones and others
// name only in client code, numbered GT icons outside the dump's meta items, the faces a texture name stands for
// (`<name>_top`, `<name>_side`, …) and fluids without a still. Pure lookups over the loaded asset index, plus the
// dump's texture names for the domains a mod draws from. Only usable files count: a square, or an animation strip of
// square frames; a sprite sheet (IC2's 96×16 strips and 384×32 machine sheets) would draw squashed.

import { FACES, type Face } from '../../shared/types/assets.ts';
import { iconDomain, iconPath, type AssetFileInfo, type AssetIndex } from './index.ts';
import type { TexturesDump } from './textures-dump.ts';

export type Atlas = 'blocks' | 'items';

/** Lookups over the usable files below every `<domain>/textures/<atlas>/` folder of an asset index. */
export interface NameIndex {
  /** `path` itself, else its only case-insensitive match; null when neither is a usable file. */
  file(path: string): string | null;
  /** The only usable file named `base` anywhere below `root` (`<domain>/textures/<atlas>/`). */
  unique(root: string, base: string): string | null;
  /** The only usable file named `base` anywhere below any domain's `textures/<atlas>/`. */
  uniqueAnywhere(atlas: Atlas, base: string): string | null;
}

/** GT's generic still texture, which GT draws in the colour of a fluid that has no texture of its own. */
export const AUTOGENERATED_FLUID = 'gregtech/textures/blocks/fluids/fluid.autogenerated.png';

/** `<domain>/textures/<atlas>/`, then the rest of a texture's path. */
const ATLAS_FILE = /^([^/]+\/textures\/(blocks|items)\/).+$/;
const LEADING_KIND = /^(?:item|tile|block)\./i;
/** In `items/` a name keeps a trailing `Block`: without it an ItemBlock's name is its material's (`diamond_block` → the gem). */
const TRAILING_KIND: Record<Atlas, RegExp> = { blocks: /(?:Block|_block|Item|_item)$/, items: /(?:Item|_item)$/ };
const FACE_SUFFIXES: Record<Face, readonly string[]> = {
  down: ['_bottom', '_top'], up: ['_top'], north: ['_front', '_side'], south: ['_back', '_side'], west: ['_side'], east: ['_side'],
};
const PNG = '.png';
const MOLTEN = '.molten';

const NAME_INDEXES = new WeakMap<AssetIndex, NameIndex>();
const MOD_DOMAINS = new WeakMap<TexturesDump, Map<string, string[]>>();

function compareText(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** A square, or an animation strip of square frames. */
function usable(info: AssetFileInfo | undefined): boolean {
  if (info === undefined || info.w <= 0) return false;
  return info.w === info.h || (info.frames !== undefined && info.frames > 1 && info.h % info.w === 0);
}

function addTo(map: Map<string, string[]>, key: string, path: string): void {
  const list = map.get(key);
  if (list === undefined) map.set(key, [path]);
  else list.push(path);
}

function only(list: readonly string[] | undefined): string | null {
  return list !== undefined && list.length === 1 ? list[0]! : null;
}

function buildNameIndex(index: AssetIndex): NameIndex {
  const byLowerPath = new Map<string, string[]>();
  const byRoot = new Map<string, Map<string, string[]>>();                       // root → basename → paths
  const byAtlas: Record<Atlas, Map<string, string[]>> = { blocks: new Map(), items: new Map() };   // basename → paths
  for (const path of Object.keys(index.file?.files ?? {})) {
    const match = ATLAS_FILE.exec(path);
    if (match === null || !usable(index.info(path))) continue;
    const root = match[1]!;
    const base = path.slice(path.lastIndexOf('/') + 1);
    let bases = byRoot.get(root);
    if (bases === undefined) {
      bases = new Map();
      byRoot.set(root, bases);
    }
    addTo(byLowerPath, path.toLowerCase(), path);
    addTo(bases, base, path);
    addTo(byAtlas[match[2] as Atlas], base, path);
  }
  return {
    file(path) {
      const matches = byLowerPath.get(path.toLowerCase());   // one lookup: nearly every path asked for is missing
      return matches === undefined ? null : matches.includes(path) ? path : only(matches);
    },
    unique: (root, base) => only(byRoot.get(root)?.get(base)),
    uniqueAnywhere: (atlas, base) => only(byAtlas[atlas].get(base)),
  };
}

/** The name index of `index`, built on first use and kept as long as the index is. */
export function nameIndex(index: AssetIndex): NameIndex {
  let names = NAME_INDEXES.get(index);
  if (names === undefined) {
    names = buildNameIndex(index);
    NAME_INDEXES.set(index, names);
  }
  return names;
}

/**
 * The file stems a registry name may use: the name, the name without a leading `item.`, `tile.` or `block.` (any
 * case), its last `.`-separated segment, then each of those without a trailing `Block`, `_block`, `Item` or `_item`
 * (in `items/` only `Item` or `_item`); empty and repeated stems are dropped.
 */
export function stemsOf(registryName: string, atlas: Atlas): string[] {
  const out: string[] = [];
  const add = (stem: string): void => {
    if (stem !== '' && !out.includes(stem)) out.push(stem);
  };
  const bare = registryName.replace(LEADING_KIND, '');
  const named = [registryName, bare, bare.slice(bare.lastIndexOf('.') + 1)];
  for (const stem of named) add(stem);
  for (const stem of named) add(stem.replace(TRAILING_KIND[atlas], ''));
  return out;
}

/** The file names (without `.png`) a stem may use for `meta` on `face`, in the order they are tried. */
export function stemCandidates(stem: string, meta: number, face: Face): string[] {
  const out = [`${stem}/${meta}`];                    // a numbered folder, as GT's meta items have
  if (meta > 0) out.push(`${stem}_${meta}`, `${stem}.${meta}`);
  out.push(stem);
  if (meta === 0) out.push(`${stem}_0`, `${stem}.0`);
  for (const suffix of FACE_SUFFIXES[face]) out.push(`${stem}${suffix}`);
  out.push(`${stem}_normal`);
  if (meta > 0) out.push(`${stem}_0`);
  out.push(`${stem}_stage_0`);
  return out;
}

/** Per mod id, the domains its texture names use, most used first, ties by name. */
function domainTable(dump: TexturesDump): Map<string, string[]> {
  const uses = new Map<string, Map<string, number>>();
  for (const names of [dump.textureNames.items, dump.textureNames.blocks]) {
    for (const [id, name] of names) {
      const colon = id.indexOf(':');
      if (colon < 0) continue;
      const mod = id.slice(0, colon);
      let counts = uses.get(mod);
      if (counts === undefined) {
        counts = new Map();
        uses.set(mod, counts);
      }
      const domain = iconDomain(name);
      counts.set(domain, (counts.get(domain) ?? 0) + 1);
    }
  }
  const table = new Map<string, string[]>();
  for (const [mod, counts] of uses) table.set(mod, [...counts].sort((a, b) => b[1] - a[1] || compareText(a[0], b[0])).map(([domain]) => domain));
  return table;
}

/**
 * The texture domains a mod's files are looked for in: the mod id lower-cased, then every other domain the mod's own
 * texture names (items and blocks) use, most used first, ties by name; a texture name without `:` counts as
 * `minecraft`. Without a dump, the mod id alone.
 */
export function modDomains(dump: TexturesDump | null, mod: string): string[] {
  const own = mod.toLowerCase();
  if (dump === null) return [own];
  let table = MOD_DOMAINS.get(dump);
  if (table === undefined) {
    table = domainTable(dump);
    MOD_DOMAINS.set(dump, table);
  }
  return [own, ...(table.get(mod) ?? []).filter((domain) => domain !== own)];
}

/**
 * The file of registry name `registryName` (without its mod) for `meta` on `face` in `atlas`: each stem's candidates
 * in each domain, then each stem's only file of that basename below a domain's atlas folder; first hit wins.
 */
export function fileByName(names: NameIndex, domains: readonly string[], registryName: string, meta: number, atlas: Atlas, face: Face): string | null {
  const stems = stemsOf(registryName, atlas);
  for (const stem of stems) {
    const candidates = stemCandidates(stem, meta, face);
    for (const domain of domains) {
      const root = `${domain}/textures/${atlas}/`;
      for (const candidate of candidates) {
        const found = names.file(`${root}${candidate}${PNG}`);
        if (found !== null) return found;
      }
    }
  }
  for (const stem of stems) {
    for (const domain of domains) {
      const found = names.unique(`${domain}/textures/${atlas}/`, `${stem}${PNG}`);
      if (found !== null) return found;
    }
  }
  return null;
}

/** Each face's file by `find`; a face that finds none takes the first face, in `FACES` order, that did. Null when none did. */
function eachFace(find: (face: Face) => string | null): Record<Face, string> | null {
  const found: Partial<Record<Face, string>> = {};
  for (const face of FACES) {
    const path = find(face);
    if (path !== null) found[face] = path;
  }
  const first = FACES.find((face) => found[face] !== undefined);
  if (first === undefined) return null;
  const out = {} as Record<Face, string>;
  for (const face of FACES) out[face] = found[face] ?? found[first]!;
  return out;
}

/** A block's six files in `blocks/` by registry name, each face by itself; null when no face finds one. */
export function facesByName(names: NameIndex, domains: readonly string[], registryName: string, meta: number): Record<Face, string> | null {
  return eachFace((face) => fileByName(names, domains, registryName, meta, 'blocks', face));
}

/** The file a texture name stands for on `face`: its stem's candidates in its own folder (no basename search). */
export function textureNameFile(names: NameIndex, iconName: string, atlas: Atlas, meta: number, face: Face): string | null {
  const path = iconPath(iconName, atlas);
  const slash = path.lastIndexOf('/');
  const folder = path.slice(0, slash + 1);
  const stem = path.slice(slash + 1, -PNG.length);
  if (stem === '') return null;
  for (const candidate of stemCandidates(stem, meta, face)) {
    const found = names.file(`${folder}${candidate}${PNG}`);
    if (found !== null) return found;
  }
  return null;
}

/** A block's six files beside its texture name (`pumpkin` → `pumpkin_top`, `pumpkin_side`); null when no face finds one. */
export function textureNameFaces(names: NameIndex, iconName: string, meta: number): Record<Face, string> | null {
  return eachFace((face) => textureNameFile(names, iconName, 'blocks', meta, face));
}

/**
 * The still texture of fluid `fluid` by name, first usable: GT's `fluid.<name>`, vanilla's `<name>_still`, IC2's
 * `fluids/<name without ic2>_still`, TiC's `liquid_<name>` (also for `<name>.molten`), then the only file below any
 * domain's `blocks/` named `<name>_still`, `fluid.<name>`, `liquid_<name>` or `fluid<Name>_still`.
 */
export function fluidFile(names: NameIndex, fluid: string): string | null {
  if (fluid === '') return null;
  const paths = [`gregtech/textures/blocks/fluids/fluid.${fluid}${PNG}`, `minecraft/textures/blocks/${fluid}_still${PNG}`];
  if (fluid.startsWith('ic2')) paths.push(`ic2/textures/blocks/fluids/${fluid.slice('ic2'.length)}_still${PNG}`);
  paths.push(`tinker/textures/blocks/liquid_${fluid}${PNG}`);
  if (fluid.endsWith(MOLTEN)) paths.push(`tinker/textures/blocks/liquid_${fluid.slice(0, -MOLTEN.length)}${PNG}`);
  for (const path of paths) {
    const found = names.file(path);
    if (found !== null) return found;
  }
  const upper = fluid.charAt(0).toUpperCase() + fluid.slice(1);
  for (const base of [`${fluid}_still${PNG}`, `fluid.${fluid}${PNG}`, `liquid_${fluid}${PNG}`, `fluid${upper}_still${PNG}`]) {
    const found = names.uniqueAnywhere('blocks', base);
    if (found !== null) return found;
  }
  return null;
}
