import { beforeAll, describe, expect, it } from 'vitest';
import { join } from 'node:path';
import { activeExportDir, loadConfig } from '../../../src/server/config.ts';
import { loadPack } from '../../../src/server/pack/load.ts';
import { loadAssetIndex, type AssetIndex } from '../../../src/server/assets/index.ts';
import { loadTexturesDump } from '../../../src/server/assets/textures-dump.ts';
import { loadNeiIndex } from '../../../src/server/assets/nei.ts';
import { curatedIds } from '../../../src/server/assets/curated.ts';
import { resolveBlocks, resolveIcons, type AssetSources } from '../../../src/server/assets/resolve.ts';
import { FACES } from '../../../src/shared/types/assets.ts';
import { legacyMteId } from '../../../src/shared/ids.ts';
import type { Pack } from '../../../src/shared/types/pack.ts';

const GT = 'gregtech/textures/blocks/';
/** Curated blocks this pack does not register: GTNH turns compacting drawers off (config/StorageDrawers.cfg compdrawers B:enabled=false). */
const DISABLED_IN_PACK = new Set(['StorageDrawers:compDrawers']);

describe.skipIf(process.env.GTNH_LOCAL !== '1')('real assets (GTNH 2.9.0-RC-1)', () => {
  let index: AssetIndex;
  let src: AssetSources;
  let pack: Pack;   // the whole pack: AssetSources.pack is a PackView, which has no fluids
  beforeAll(async () => {
    const cfg = loadConfig();
    index = await loadAssetIndex(join(cfg.dataDir, 'assets'));
    const exportDir = activeExportDir(cfg);
    pack = await loadPack(exportDir);
    src = { index, dump: await loadTexturesDump(exportDir, index), nei: await loadNeiIndex(join(cfg.dataDir, 'assets')), pack };
  }, 300_000);

  it('extracted the mod jars and the official client jar', () => {
    expect(index.size).toBeGreaterThan(40_000);   // research §2.2's 50,205 mod PNGs are every textures/ folder; the block and item atlases hold 43,972 + 562 vanilla
    expect(index.file!.sources.find((s) => s.kind === 'client')!.sha1).toBe('e80d9b3bf5085002218d4be59e668bac718abbc6');
    expect(index.has('minecraft/textures/blocks/stone.png')).toBe(true);
    expect(index.info(GT + 'fluids/fluid.autogenerated.png')).toMatchObject({ w: 16, h: 512, frames: 32 });   // research §2.4
    expect(index.file!.conflicts.find((c) => c.path === 'gregtech/textures/items/gt.metaitem.01/606.png')!.winner).toMatch(/^GTNewHorizonsCoreMod/);
  });

  it('has a texture dump that reconstructs GT machines and casings', () => {
    const d = src.dump!;
    expect(d.mte.size).toBeGreaterThan(2_000);
    expect([...d.mte.values()].filter((m) => m.error).length / d.mte.size).toBeLessThan(0.05);
    expect(d.textureNames.blocks.has('gregtech:gt.blockmachines')).toBe(false);          // else an unknown MTE would draw that texture
    const failed = [...d.mte].find(([, m]) => m.error !== undefined)![0];
    expect(resolveBlocks(src, [{ id: 'gregtech:gt.blockmachines', meta: 0, mteId: failed }])[0]!.resolved).toBe(false);   // not the hull of d.blocks
    const [mac] = resolveBlocks(src, [{ id: 'gregtech:gt.blockmachines', meta: 0, mteId: 301 }]);       // MACERATOR_LV, research §3.3
    const glow = index.has(GT + 'basicmachines/macerator/OVERLAY_FRONT_GLOW.png');
    expect(mac!.faces.north.map((l) => l.path)).toEqual([GT + 'iconsets/MACHINE_LV_SIDE.png', GT + 'basicmachines/macerator/OVERLAY_FRONT.png',
      ...(glow ? [GT + 'basicmachines/macerator/OVERLAY_FRONT_GLOW.png'] : [])]);
    const topGlow = index.has(GT + 'basicmachines/macerator/OVERLAY_TOP_GLOW.png');
    expect(mac!.faces.up.map((l) => l.path)).toEqual([GT + 'iconsets/MACHINE_LV_TOP.png', GT + 'basicmachines/macerator/OVERLAY_TOP.png',
      ...(topGlow ? [GT + 'basicmachines/macerator/OVERLAY_TOP_GLOW.png'] : [])]);
    if (glow) expect(mac!.faces.north.at(-1)!.glow).toBe(true);
    if (topGlow) expect(mac!.faces.up.at(-1)!.glow).toBe(true);
    const bottom = ['OVERLAY_BOTTOM.png', 'OVERLAY_BOTTOM_GLOW.png'].map((f) => GT + 'basicmachines/macerator/' + f).filter((p) => index.has(p));
    expect(mac!.faces.down.map((l) => l.path)).toEqual([GT + 'iconsets/MACHINE_LV_BOTTOM.png', ...bottom]);   // a pack's optional overlays, drawn when the file exists
    expect(mac!.faces.down.slice(1).map((l) => l.glow === true)).toEqual(bottom.map((p) => p.endsWith('_GLOW.png')));
    expect(resolveBlocks(src, [{ id: 'gregtech:gt.blockcasings2', meta: 0 }])[0]!.faces.up.map((l) => l.path)).toEqual([GT + 'iconsets/MACHINE_CASING_SOLID_STEEL.png']);
    expect(resolveBlocks(src, [{ id: 'gregtech:gt.blockcasings2', meta: 1 }])[0]!.faces.north.map((l) => l.path)).toEqual([GT + 'iconsets/MACHINE_CASING_FROST_PROOF.png']);   // research §3.7
  });

  it('draws GT material items and GT fluids from the game files', () => {
    const [ingot, molten] = resolveIcons(src, ['gregtech:gt.metaitem.01@11032', 'fluid:molten.iron']);
    const ingotOverlay = 'gregtech/textures/items/materialicons/METALLIC/ingot_OVERLAY.png';   // a pack's: GT draws a texture set's _OVERLAY when the file exists
    expect(ingot).toMatchObject({ source: 'gt', layers: [{ tint: [200, 200, 200] }, ...(index.has(ingotOverlay) ? [{ path: ingotOverlay }] : [])] });
    if (index.has(ingotOverlay)) expect(ingot!.layers[1]).toEqual({ path: ingotOverlay });   // untinted
    expect(ingot!.layers[0]!.path).toMatch(/^gregtech\/textures\/items\/materialicons\//);
    expect(molten!.source).toBe('gt');
    expect(molten!.layers[0]!.path).toBe(GT + 'fluids/fluid.molten.autogenerated.png');
    const [ore] = resolveIcons({ ...src, nei: null }, ['gregtech:gt.blockores2@32']);   // Iron Ore: GTBlockOre draws its stone under the tinted ore icon
    expect(ore!.source).toBe('gt');
    expect(ore!.layers.slice(0, 2)).toMatchObject([{ path: 'minecraft/textures/blocks/stone.png' }, { tint: [200, 200, 200] }]);
    expect(ore!.layers[1]!.path).toMatch(/^gregtech\/textures\/blocks\/materialicons\/.+\/ore\.png$/);
    expect(resolveIcons(src, ['gregtech:gt.blockores2@32'])[0]!.source).toBe('nei');   // item icons with an NEI dump icon keep it (spec, 2026-10-23)
  });

  it('every curated entry names a real block and an extracted texture', () => {
    const pseudo = /^(fmp|conduit|ae2cable):/;
    expect(curatedIds().filter((id) => !pseudo.test(id) && !DISABLED_IN_PACK.has(id) && !src.dump!.blockIds.has(id))).toEqual([]);
    const broken = curatedIds().flatMap((id) => {
      const b = resolveBlocks(src, [{ id, meta: 0 }])[0]!;
      return FACES.filter((f) => b.faces[f].length === 0).map((f) => `${id} ${f}`);
    });
    expect(broken).toEqual([]);
  });

  it('extracted no two textures whose paths differ only in case', () => {
    const seen = new Map<string, string>();
    const clashes: string[] = [];
    for (const path of Object.keys(index.file!.files)) {
      const other = seen.get(path.toLowerCase());
      if (other === undefined) seen.set(path.toLowerCase(), path);
      else clashes.push(`${other} | ${path}`);
    }
    expect(clashes).toEqual([]);                                                            // the Mac's disk would keep only one of each pair
  });

  it('reports coverage', () => {
    const machines = [...pack.machines.keys()].map((id) => ({ id: 'gregtech:gt.blockmachines', meta: 0, mteId: legacyMteId(id) }));
    const blocks = resolveBlocks(src, machines);
    const keys = [...pack.items.keys(), ...pack.fluids.keys()];
    const icons = resolveIcons(src, keys);
    const machineShare = blocks.filter((b) => b.resolved).length / blocks.length;
    const iconShare = icons.filter((i) => i.source !== 'fallback').length / icons.length;
    console.log(`machines fully textured ${(100 * machineShare).toFixed(1)} %, icons from the game ${(100 * iconShare).toFixed(1)} % of ${keys.length}, `
      + `dropped layers ${src.dump!.stats.droppedLayers}`);
    expect(machineShare).toBeGreaterThan(0.9);
    // without NEI: GT items, ore blocks, fluids and the few classes that set iconString (research §6.4)
    expect(iconShare).toBeGreaterThan(src.nei ? 0.41 : 0.25);   // measured 2026-10-23 with NEI and the user's packs; the old 0.9 predates the NEI import
  });
});

const PACKS = { uu: 'UU-Tex-main', mod: 'Modernity-GTNH-2026-08-31.zip' };
describe.skipIf(process.env.GTNH_LOCAL !== '1' || !loadConfig().clientInstance)('real resource packs', () => {
  let index: AssetIndex;
  beforeAll(async () => { index = await loadAssetIndex(join(loadConfig().dataDir, 'assets')); });

  it('recorded the enabled packs and what each supplied', (ctx) => {
    if (!index.file?.packs) ctx.skip();   // an index made with --no-packs or before the packs run
    const packs = index.file!.packs!;
    expect(packs.read.map((p) => p.name)).toEqual(packs.enabled.filter((n) => packs.read.some((p) => p.name === n)));
    const supplied = new Map<string, number>();
    for (const info of Object.values(index.file!.files)) supplied.set(info.jar, (supplied.get(info.jar) ?? 0) + 1);
    for (const p of packs.read) expect(supplied.get(p.name) ?? 0, p.name).toBe(p.files);
  });

  it('layers the packs as the game does', (ctx) => {
    if (!index.file?.packs) ctx.skip();
    const read = new Set(index.file!.packs!.read.map((p) => p.name));
    if (read.has(PACKS.mod)) {
      expect(index.info('minecraft/textures/blocks/stone.png')!.jar).toBe(PACKS.mod);
      expect(index.info('ae2fc/textures/blocks/fluid_packet_decoder.png')).toMatchObject({ jar: PACKS.mod, frames: 22 });   // still in the jar
      expect(index.has('dreamcraft/textures/blocks/blockPixieDust.png')).toBe(false);   // a JPEG named .png: left out, no jar fallback
      expect(index.has('goodgenerator/textures/items/plasticcase.png')).toBe(false);   // the zip's spelling differs only in case
    }
    if (read.has(PACKS.uu)) {
      expect(index.info('gregtech/textures/blocks/iconsets/MACHINE_CASING_FIREBOX_BRONZE_TOP.png')!.jar).toBe(PACKS.uu);
      expect(index.info('littletiles/textures/items/LTRecipe.png')!.jar).toBe(PACKS.uu);   // the folder spells it ltrecipe.png
      expect(index.info('goodgenerator/textures/items/plasticCase.png')!.jar).toBe(PACKS.uu);
    }
  });
});
