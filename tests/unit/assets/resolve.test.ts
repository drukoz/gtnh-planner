import { describe, it, expect } from 'vitest';
import { gtSampleFile, GT_SAMPLE_ASSETS, I, BM, MI } from '../../helpers/gt-sample.ts';
import { indexOf, type AssetSpec } from '../../helpers/assets-dir.ts';
import { dumpFile } from '../../helpers/textures-dump.ts';
import { AUTOGENERATED_FLUID, modDomains } from '../../../src/server/assets/names.ts';
import { buildTexturesDump, type DumpFaces, type DumpLayer, type TexturesDumpFile } from '../../../src/server/assets/textures-dump.ts';
