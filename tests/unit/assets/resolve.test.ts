    expect(resolveBlocks(only({ [OBSIDIAN]: {}, [ENDER]: { w: 64, h: 64 } }), [ender])[0]!.faces.west)
      .toEqual([crop(ENDER, [28, 33, 14, 10], [1, 6, 14, 10]), crop(ENDER, [28, 14, 14, 5], [1, 2, 14, 5])]);
