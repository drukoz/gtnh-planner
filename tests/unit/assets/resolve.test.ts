    [MB + 'NONE/frameGt.png']: {},   // no frameGt_OVERLAY: the frame has one layer
    [MI + 'NONE/dust.png']: {}, [MI + 'NONE/dust_OVERLAY.png']: {}, [MI + 'NONE/cell.png']: {}, [MI + 'NONE/cell_OVERLAY.png']: {},
    [MI + 'NONE/cellPlasma.png']: {}, [MI + 'NONE/cellPlasma_OVERLAY.png']: {},
